"""Helpers to produce blobs outside the client upload flow."""

import hashlib
import logging
from io import BytesIO

from django.core.files.storage import default_storage

from core.models import Blob, ItemUploadStateChoices

logger = logging.getLogger(__name__)


def store_content_as_blob(content: bytes) -> Blob:
    """
    Write content under its content-addressed key blobs/<sha256> and return the Blob.

    Used by server-side producers (file templates, conversion): the content is
    generated by the server, so a newly created blob is READY directly, without
    antivirus analysis. Existing blobs keep their own analysis state.
    """
    digest = hashlib.sha256(content).hexdigest()
    blob, _created = Blob.objects.get_or_create(
        hash=digest,
        defaults={"size": len(content), "upload_state": ItemUploadStateChoices.READY},
    )
    if not default_storage.exists(blob.file_key):
        default_storage.save(blob.file_key, BytesIO(content))
    return blob
